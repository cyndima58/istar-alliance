def ntf(items):
    return '<div class="ntf">' + "".join(
        f'<div><span class="dot">{I[ic]}</span><p style="margin:0"><b>{t}</b><span>{d}</span></p></div>' for ic, t, d in items) + "</div>"

def feature(tag, cls, title, side, items):
    lis = "".join(f"<li>{x}</li>" for x in items)
    return f'''<div class="feature"><div class="side"><span class="tag {cls}">{tag}</span><h3>{title}</h3><p>{side}</p></div><div class="body"><ul>{lis}</ul></div></div>'''

def faq(items):
    return "".join(f"<details><summary>{q}</summary><div>{a}</div></details>" for q, a in items)

